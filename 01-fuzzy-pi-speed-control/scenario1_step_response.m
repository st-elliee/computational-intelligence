%% -----------------------------------------------------------
%  Σενάριο 1 – Βηματική απόκριση & ρύθμιση FZ-PI
%
%  Το FIS πρέπει να έχει δημιουργηθεί από το design_FLC_FZPI.m
%  Απαιτούμενα αρχεία:
%    - pi_tuned_params.mat        (από pi_design_trapezi_ergasias.m)
%    - flc_corrected_params.mat   (από design_FLC_FZPI.m)
%% -----------------------------------------------------------

clear; clc; close all;

%% -----------------------------------------------------------
%  1.  ΦΟΡΤΩΣΗ PI ΚΑΙ FLC ΠΑΡΑΜΕΤΡΩΝ
%% -----------------------------------------------------------

% ΔΙΟΡΘΩΣΗ: το σωστό όνομα αρχείου είναι flc_corrected_params.mat
load('pi_tuned_params.mat',       'Kp','Ki','c','w_step');
load('flc_corrected_params.mat',  'FLC');

fis = FLC.fis;

fprintf('\n=== Φόρτωση PI κερδών ===\n');
fprintf('  Kp     = %.4f\n', Kp);
fprintf('  Ki     = %.4f\n', Ki);
fprintf('  w_step = %.1f rad/s\n', w_step);

%% -----------------------------------------------------------
%  2.  ΚΕΡΔΗ ΚΛΙΜΑΚΟΠΟΙΗΣΗΣ
%
%  Ke    : e ∈ [-50,50] → [-1,1]        Ke = 1/50 = 0.02
%
%  alpha : de(k) = (e(k)-e(k-1)) / T   [rad/s²]
%          Worst case: |Δe| = 2×50=100, T=0.01
%          max|de| = 100/0.01 = 10000
%          alpha = 1/10000 = T/max_delta_e = 0.0001
%
%  K1    : έξοδος FLC κλιμακοποιείται με Ki (ολοκληρωτικός όρος PI)
%
%  Αρχικές τιμές = αυτές του γραμμικού PI.
%  Στη συνέχεια ρυθμίζονται (βλ. ενότητα 5) για OS<5%, tr<0.6s.
%% -----------------------------------------------------------

T = 0.01;        % δειγματοληψία (sec)

Ke    = 0.04;        
alpha = 0.015;     
K1    = 4.0;            

fprintf('\n=== Scaling Gains (αρχικές τιμές) ===\n');
fprintf('  Ke    = %.6f\n', Ke);
fprintf('  alpha = %.6f\n', alpha);
fprintf('  K1    = %.6f\n', K1);

%% -----------------------------------------------------------
%  3.  ΦΥΤΟ & ΓΡΑΜΜΙΚΟΣ PI ΚΛΕΙΣΤΟΣ ΒΡΟΧΟΣ (για σύγκριση)
%% -----------------------------------------------------------

s    = tf('s');
Gp   = 25 / ((s+0.1)*(s+10));
Gc   = Kp + Ki/s;
T_PI = feedback(Gc * Gp, 1);

%% -----------------------------------------------------------
%  4.  STATE-SPACE ΦΥΤΟΥ (EULER FORWARD, ΔΙΑΚΡΙΤΟΣ ΧΡΟΝΟΣ)
%
%  Gp(s) = 25/[(s+0.1)(s+10)] = 25/(s²+10.1s+1)
%
%  Επιλογή state: x1=y, x2=dy/dt
%       ẋ = Ac*x + Bc*u
%       y  = Cc*x
%
%  Αριθμητική ολοκλήρωση: x(k+1) = x(k) + T * f(x(k), u(k))
%% -----------------------------------------------------------

Ac = [0,    1;
     -1, -10.1];
Bc = [0; 25];
Cc = [1, 0];

%% -----------------------------------------------------------
%  5.  ΠΡΟΣΟΜΟΙΩΣΗ FZ-PI (ΒΗΜΑΤΙΚΗ ΕΙΣΟΔΟΣ r = 50 rad/s)
%% -----------------------------------------------------------

t_end = 5;
t     = 0:T:t_end;
N     = length(t);

r  = w_step * ones(1, N);   % βηματική αναφορά

y  = zeros(1, N);
u  = zeros(1, N);
e  = zeros(1, N);
de = zeros(1, N);
x  = zeros(2, 1);

for k = 2:N

    %-- Σφάλμα
    e(k)  = r(k) - y(k-1);

    %-- Μεταβολή σφάλματος (παράγωγος)
    de(k) = (e(k) - e(k-1)) / T;

    %-- Κανονικοποίηση → [-1,1]
    e_n  = Ke    * e(k);
    de_n = alpha * de(k);

    %-- Saturation (προφύλαξη για εξωτερικές διαταραχές)
    e_n  = max(-1, min(1, e_n));
    de_n = max(-1, min(1, de_n));

    %-- Ασαφής ελεγκτής → κανονικοποιημένη μεταβολή ελέγχου
    du_n = evalfis(fis, [e_n, de_n]);

    %-- Αποκανονικοποίηση
    du = K1 * du_n;

    %-- Incremental (PI) ολοκλήρωση
    u(k) = u(k-1) + du;

    %-- Anti-windup saturation (ΔΙΟΡΘΩΣΗ: συμμετρικό εύρος ±200)
    %   Το u είναι είσοδος φυτού (τάση), ΟΧΙ ταχύτητα.
    %   Ένα λογικό εύρος εξάγεται από DC gain: y_ss = Gp(0)*u_ss
    %   Gp(0) = 25/(0.1*10) = 25, άρα u_ss ≈ w_step/25 = 2 rad/s²
    %   Δίνουμε αρκετή ελευθερία: [-50, 50]
    u(k) = max(-50, min(50, u(k)));

    %-- Φυτό (Euler forward)
    xdot = Ac * x + Bc * u(k);
    x    = x + T * xdot;
    y(k) = Cc * x;

end

%% -----------------------------------------------------------
%  6.  ΜΕΤΡΙΚΑ FZ-PI
%% -----------------------------------------------------------

infoFLC = stepinfo(y, t, w_step, 'SettlingTimeThreshold', 0.02);
ss_error = abs(w_step - y(end));

fprintf('\n=== Μετρικά FZ-PI (αρχικά κέρδη) ===\n');
fprintf('  Overshoot (%%)     = %.3f\n', infoFLC.Overshoot);
fprintf('  Rise time (s)     = %.3f\n', infoFLC.RiseTime);
fprintf('  Settling time (s) = %.3f\n', infoFLC.SettlingTime);
fprintf('  Steady-state err  = %.4f rad/s\n', ss_error);
fprintf('  max(u)            = %.3f\n', max(u));
fprintf('  min(u)            = %.3f\n', min(u));

specs_ok = (infoFLC.Overshoot < 5) && (infoFLC.RiseTime < 0.6);
if specs_ok
    fprintf('\n  >>> ΙΚΑΝΟΠΟΙΕΙ τις προδιαγραφές (OS<5%%, tr<0.6s) ✓\n');
else
    fprintf('\n  >>> ΔΕΝ ικανοποιεί ακόμα – δοκιμάστε νέα κέρδη\n');
end

%% -----------------------------------------------------------
%  7.  ΓΡΑΦΙΚΗ ΣΥΓΚΡΙΣΗ PI vs FZ-PI
%% -----------------------------------------------------------

[y_PI, t_PI] = step(w_step * T_PI, t_end);

figure('Name','Σύγκριση PI vs FZ-PI','Color','w');
plot(t_PI, y_PI, 'b-',  'LineWidth', 1.5); hold on;
plot(t,    y,    'r-',  'LineWidth', 1.5);
yline(w_step, '--k', 'LineWidth', 1.0);
grid on;
xlabel('Χρόνος (s)');
ylabel('Ταχύτητα (rad/s)');
legend('Γραμμικός PI', 'FZ-PI', 'Αναφορά', 'Location','southeast');
title(sprintf('Βηματική απόκριση r=%g rad/s – Σύγκριση PI vs FZ-PI', w_step));
xlim([0, t_end]); ylim([0, w_step*1.15]);

%% -----------------------------------------------------------
%  8.  ΕΠΙΔΡΑΣΗ ΚΕΡΔΩΝ ΚΛΙΜΑΚΟΠΟΙΗΣΗΣ
%     Δείχνουμε πώς τα Ke, alpha, K1 επηρεάζουν την απόκριση
%% -----------------------------------------------------------

fprintf('\n=== Επίδραση κερδών κλιμακοποίησης ===\n');
fprintf('  Ke    : αυξάνει → μεγαλύτερο εύρος e_n → ταχύτερη απόκριση\n');
fprintf('          μειώνει → μικρότερο εύρος e_n → πιο σταθερή αλλά βραδύτερη\n');
fprintf('  alpha : αυξάνει → μεγαλύτερο εύρος de_n → ισχυρότερη απόσβεση\n');
fprintf('          μειώνει → μικρότερο εύρος de_n → λιγότερη απόσβεση\n');
fprintf('  K1    : αυξάνει → πιο επιθετικός ελεγκτής (κίνδυνος υπερύψωσης)\n');
fprintf('          μειώνει → πιο αργός ελεγκτής (μικρότερη υπερύψωση)\n');

%% -----------------------------------------------------------
%  9.  ΣΕΝΑΡΙΟ 1β – ΕΝΕΡΓΟΠΟΙΗΣΗ ΚΑΝΟΝΩΝ ΓΙΑ e=NS, dE=NS
%
%  Κανονικοποιημένες τιμές εισόδου:
%    NS = κέντρο στο -1/3 ≈ -0.333
%  Δοκιμάζουμε ακριβώς στο κέντρο ΝS.
%% -----------------------------------------------------------

e_test  = -1/3;     % κέντρο MF "NS" για E
de_test = -1/3;     % κέντρο MF "NS" για dE

du_test = evalfis(fis, [e_test, de_test]);

fprintf('\n=== Σενάριο 1β: e is NS, Δe is NS ===\n');
fprintf('  e_n  = %.4f  (κέντρο NS)\n', e_test);
fprintf('  de_n = %.4f  (κέντρο NS)\n', de_test);
fprintf('  du_n = %.4f  (κανονικοποιημένο)\n', du_test);
fprintf('  du   = %.4f  (πραγματικό, ×K1=%.4f)\n', K1*du_test, K1);
fprintf('\n  Φυσική ερμηνεία:\n');
fprintf('  Αρνητικό σφάλμα (NS) ΚΑΙ αρνητική μεταβολή (NS)\n');
fprintf('  → το σύστημα απομακρύνεται από την αναφορά\n');
fprintf('  → ο FLC εκδίδει αρνητική αύξηση du → μειώνει u(k)\n');
fprintf('  → απόκριση: μικρή αρνητική μεταβολή ελέγχου\n');

% Γραφική απεικόνιση βάσης κανόνων
figure('Name','Rule Viewer: e=NS, dE=NS','Color','w');
ruleview(fis);
% Στο παράθυρο που ανοίγει: βάλτε input1=-0.333, input2=-0.333

%% -----------------------------------------------------------
%  10. ΣΕΝΑΡΙΟ 1γ – 3D ΕΠΙΦΑΝΕΙΑ ΝΟΜΟΥ ΕΛΕΓΧΟΥ
%% -----------------------------------------------------------

figure('Name','3D Επιφάνεια FLC','Color','w');
gensurf(fis);
title('Νόμος ελέγχου FZ-PI: dU = f(E, dE)');
xlabel('E (κανονικοποιημένο σφάλμα)');
ylabel('dE (κανονικοποιημένη μεταβολή)');
zlabel('dU (κανονικοποιημένη μεταβολή ελέγχου)');
colorbar;

fprintf('\n=== Ερμηνεία 3D επιφάνειας ===\n');
fprintf('  - Αντισυμμετρική ως προς την αρχή → σωστή PI συμπεριφορά\n');
fprintf('  - Κορεσμός στις γωνίες (NL,NL)→NV και (PL,PL)→PV\n');
fprintf('  - Γραμμική συμπεριφορά κοντά στην ισορροπία (ZR,ZR)→ZR\n');
fprintf('  - Η "κλίση" στον άξονα E → αναλογική δράση\n');
fprintf('  - Η "κλίση" στον άξονα dE → παραγωγική/αποσβεστική δράση\n');

%% -----------------------------------------------------------
%  11. ΑΠΟΘΗΚΕΥΣΗ ΑΠΟΤΕΛΕΣΜΑΤΩΝ
%% -----------------------------------------------------------

save('scenario1_results.mat', 't', 'y', 'u', 'e', 'de', ...
     'y_PI', 't_PI', 'Ke', 'alpha', 'K1', 'infoFLC');

fprintf('\n=== Αποθήκευση → scenario1_results.mat ===\n');